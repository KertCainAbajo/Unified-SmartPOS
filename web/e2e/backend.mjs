// Starts the Laravel API for Playwright on its own throwaway SQLite database (never your real MySQL data):
// writes .env.e2e if it does not exist, rebuilds database/e2e.sqlite from the demo seeders, then serves on :8010.
import { execFileSync, spawn } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const envFile = join(root, '.env.e2e');
const database = join(root, 'database', 'e2e.sqlite').replaceAll('\\', '/');
export const API_PORT = 8010;
export const WEB_PORT = 5180;

if (!existsSync(envFile)) {
  writeFileSync(
    envFile,
    [
      '# Generated by web/e2e/backend.mjs for Playwright. Test-only; safe to delete.',
      'APP_NAME="Unified SmartPOS"',
      'APP_ENV=e2e',
      `APP_KEY=base64:${randomBytes(32).toString('base64')}`,
      'APP_DEBUG=true',
      `APP_URL=http://127.0.0.1:${API_PORT}`,
      `FRONTEND_URL=http://127.0.0.1:${WEB_PORT}`,
      'DB_CONNECTION=sqlite',
      `DB_DATABASE="${database}"`,
      'SESSION_DRIVER=database',
      'SESSION_DOMAIN=null',
      'CACHE_STORE=array',
      'QUEUE_CONNECTION=sync',
      'MAIL_MAILER=array',
      'LOG_CHANNEL=stderr',
      'LOG_LEVEL=warning',
      'BCRYPT_ROUNDS=4',
      `SANCTUM_STATEFUL_DOMAINS=127.0.0.1:${WEB_PORT},localhost:${WEB_PORT}`,
      'SMARTPOS_REQUIRE_EMAIL_VERIFICATION=false',
      '',
    ].join('\n'),
  );
}

const env = { ...process.env, APP_ENV: 'e2e' };
const artisan = (...args) => execFileSync('php', ['artisan', ...args], { cwd: root, env, stdio: 'inherit' });

writeFileSync(database, '');
artisan('migrate:fresh', '--force', '--no-interaction');
for (const seeder of ['RolesAndPermissionsSeeder', 'DemoSeeder', 'DemoStaffSeeder', 'DemoRecruitmentSeeder']) {
  artisan('db:seed', `--class=${seeder}`, '--force', '--no-interaction');
}

const server = spawn('php', ['artisan', 'serve', '--host=127.0.0.1', `--port=${API_PORT}`, '--no-reload'], { cwd: root, env, stdio: 'inherit' });
const stop = () => server.kill();
process.on('SIGINT', stop);
process.on('SIGTERM', stop);
process.on('exit', stop);
server.on('exit', (code) => process.exit(code ?? 0));
